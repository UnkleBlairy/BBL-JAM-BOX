#!/usr/bin/env python3
"""Render the 16x16 icons drawn in docs/808lab.html (its EX table) and docs/samplelab.html (its IC table) to C rows: one
uint16_t a row, the left pixel the top bit. Writes firmware/src/icons_808.h. Run again after the HTML's drawings change:
    python3 tools/gen_icons_808.py [docs/808lab.html] [firmware/src/icons_808.h] [docs/samplelab.html]
Only the icons icons_gb.h doesn't already have (from the Pixel Slots editor) are written."""
import math, re, sys

N = 16
WANT = [("tom", "TOM"), ("rim", "RIM"), ("clap", "CLAP"), ("cow", "COWBELL"), ("age", "AGE")]
WANT_SMP = [("smp", "SMP"), ("once", "SMP_ONCE"), ("loop", "SMP_LOOP"), ("ping", "SMP_PING"), ("rev", "SMP_REV")]   # (ui_icons.h has SAMPLE, LOOP)
SMP_BODY = ";".join("d.V(%d, %d, %d)" % (1 + 2 * i, 8 - h, 7 + h) for i, h in enumerate([2, 4, 7, 5, 3, 6, 3, 1]))   # (its loop)

def jround(v):                     # JavaScript's Math.round: halves go up
    return math.floor(v + 0.5)

def render(body):
    g = [0] * (N * N)
    def P(x, y):
        x, y = jround(x), jround(y)
        if 0 <= x < N and 0 <= y < N:
            g[y * N + x] = 1
    def L(x0, y0, x1, y1):
        dx, dy = abs(x1 - x0), -abs(y1 - y0)
        sx, sy = (1 if x0 < x1 else -1), (1 if y0 < y1 else -1)
        e = dx + dy
        while True:
            P(x0, y0)
            if x0 == x1 and y0 == y1:
                break
            e2 = 2 * e
            if e2 >= dy:
                e += dy; x0 += sx
            if e2 <= dx:
                e += dx; y0 += sy
    def poly(p):
        for i in range(len(p) - 1):
            L(p[i][0], p[i][1], p[i + 1][0], p[i + 1][1])
    def H(x0, x1, y):
        for x in range(x0, x1 + 1): P(x, y)
    def V(x, y0, y1):
        for y in range(y0, y1 + 1): P(x, y)
    def R(x, y, w, h):
        H(x, x + w - 1, y); H(x, x + w - 1, y + h - 1); V(x, y, y + h - 1); V(x + w - 1, y, y + h - 1)
    def F(x, y, w, h):
        for j in range(h): H(x, x + w - 1, y + j)
    def C(cx, cy, r):
        for y in range(N):
            for x in range(N):
                d = math.sqrt((x - cx) ** 2 + (y - cy) ** 2)
                if r - 0.6 <= d < r + 0.45: P(x, y)
    env = {"P": P, "L": L, "poly": poly, "H": H, "V": V, "R": R, "F": F, "C": C}
    for call in body.split(";"):                       # d.C(7.5, 7.5, 6.5); d.poly([[3, 9], ...]) ..
        call = call.strip()
        if call:
            eval(re.sub(r"^d\.", "", call), {"__builtins__": {}}, env)
    return g

def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "docs/808lab.html"
    dst = sys.argv[2] if len(sys.argv) > 2 else "firmware/src/icons_808.h"
    html = open(src, encoding="utf-8").read()
    ex = re.search(r"var EX = \{(.*?)\n\s*\};", html, re.S).group(1)
    fns = dict(re.findall(r"(\w+): function \(d\) \{(.*?)\}\s*,?\s*$", ex, re.M))
    out = ["/* icons_808.h - generated by tools/gen_icons_808.py from docs/808lab.html and docs/samplelab.html: 16 x 16,",
           " * one uint16_t a row, the left pixel the top bit (0x8000), like icons_gb.h. Don't edit: run the script. */",
           "#pragma once", "#include <stdint.h>", ""]
    sl = open(sys.argv[3] if len(sys.argv) > 3 else "docs/samplelab.html", encoding="utf-8").read()
    ic = re.search(r"var IC = \{(.*?)\n\s*\};", sl, re.S).group(1)
    sfns = dict(re.findall(r"(\w+): mk\(function \(d\) \{(.*?)\}\),?\s*$", ic, re.M))
    sfns["smp"] = SMP_BODY
    for key, name in WANT + WANT_SMP:
        g = render(fns[key] if (key, name) in WANT else sfns[key])
        rows = [sum(g[y * N + x] << (15 - x) for x in range(N)) for y in range(N)]
        out.append("// " + name)
        out += ["//   " + "".join("#" if g[y * N + x] else "." for x in range(N)) for y in range(N)]
        out.append("static const uint16_t ICON_%s[16] = {%s};" % (name, ", ".join("0x%04X" % r for r in rows)))
        out.append("")
    open(dst, "w").write("\n".join(out))

main()
