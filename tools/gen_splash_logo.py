"""Turn the power-on logo (a picture) into 1-bit pixel art for the splash: N x N pixels, the picture's dark lines lit
(the UI's pixel style: one ink on the background), lone specks removed. Writes firmware/src/splash_logo.h: one row of
N/8 bytes a line, the left pixel the top bit. Run again after changing the picture:
    python3 tools/gen_splash_logo.py [assets/logo/MEE.jpg] [firmware/src/splash_logo.h]"""
import sys
from PIL import Image

N = 96                  # pixels a side (drawn 2x on the screen: 192)
DARK = 75               # grey level under which a pixel is a line (0..255)


def main(src="assets/logo/MEE.jpg", out="firmware/src/splash_logo.h"):
    g = Image.open(src).convert("L").resize((N, N), Image.LANCZOS)
    px = [[g.getpixel((x, y)) < DARK for x in range(N)] for y in range(N)]
    lit = lambda x, y: 0 <= x < N and 0 <= y < N and px[y][x]
    clean = [[px[y][x] and any(lit(x + i, y + j) for i in (-1, 0, 1) for j in (-1, 0, 1) if i or j)
              for x in range(N)] for y in range(N)]
    rows = []
    for y in range(N):
        b = [sum(0x80 >> k for k in range(8) if clean[y][x * 8 + k]) for x in range(N // 8)]
        rows.append("    {" + ", ".join(f"0x{v:02X}" for v in b) + "},")
    with open(out, "w") as f:
        f.write(f"/* generated by tools/gen_splash_logo.py from {src}: the power-on logo, {N} x {N}, 1 bit (the left\n"
                f" * pixel the top bit). The logo is (C) 2026 Blair (blairysbeatlab), all rights reserved: not under the\n"
                f" * GPL (LICENSING.md). A fork replaces it with its own. */\n#pragma once\n#include <stdint.h>\n\n"
                f"#define SPLASH_LOGO_N {N}\nstatic const uint8_t SPLASH_LOGO[{N}][{N // 8}] = {{\n" + "\n".join(rows) + "\n};\n")
    print(f"{out}: {N} x {N}, {sum(map(sum, clean))} pixels lit")


if __name__ == "__main__":
    main(*sys.argv[1:3])
